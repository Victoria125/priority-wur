"""Step 7 (Experiment D). How different are the labs?

A federated study needs a measured heterogeneity between its clients. Here
every run is one lab, and the question is: can a simple classifier tell two
labs apart from the spectrum embeddings alone? Balanced accuracy 0.5 means
the labs look the same; 1.0 means they are completely separated.

Labs differ in chemistry (other genera, other molecules) and in measurement
(instrument, settings, year). To separate the two, the test is repeated on
library-annotated spectra of molecules that both labs measured: if the labs
are still told apart there, the difference comes from the measurement.
"""
import argparse
import itertools

import numpy as np
import pandas as pd
from rdkit import Chem
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import StratifiedKFold, cross_val_score

import common as C
from exp_b_structures import molecule

DEFAULT_LABS = ["duncan_salinispora", "crusemann_salstrep", "chevrette_insect",
                "dorrestein_salbus", "tahlan_streptomyces"]
OUT_DIR = C.EXPERIMENT_DIR / "lab_shift"
MAX_PER_LAB = 1500        # spectra per lab and pair (random sample), for speed
MIN_SHARED_SPECTRA = 10   # per lab, for the test on shared molecules


def load(run, variant):
    p = C.run_paths(run, variant)
    if not (p.metadata.exists() and p.embeddings.exists()):
        return None
    meta, emb = C.load_metadata_and_embeddings(p)
    reps = {"DreaMS": emb, "binned spectrum": C.binned_vectors(C.read_clean_spectra(p, meta))}
    ms2ds = C.load_ms2deepscore(p)
    if ms2ds is not None:
        reps["MS2DeepScore"] = ms2ds
    keys = []
    for smiles in meta["smiles"]:
        mol = molecule(smiles)
        keys.append(Chem.MolToInchiKey(mol)[:14] if mol is not None else "")
    return {"reps": reps, "keys": np.array(keys)}


def separability(x_a, x_b, seed=0):
    """Balanced accuracy (5-fold cross-validation) of telling lab A from lab B."""
    rng = np.random.default_rng(seed)
    n = min(len(x_a), len(x_b), MAX_PER_LAB)
    a = x_a[rng.choice(len(x_a), n, replace=False)]
    b = x_b[rng.choice(len(x_b), n, replace=False)]
    x = np.vstack([a, b])
    y = np.r_[np.zeros(n), np.ones(n)]
    folds = StratifiedKFold(n_splits=5, shuffle=True, random_state=seed)
    model = LogisticRegression(max_iter=2000, C=1.0)
    return float(cross_val_score(model, x, y, cv=folds, scoring="balanced_accuracy").mean()), n


def markdown(df):
    df = df.fillna("").astype(str)
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    return "\n".join(lines + ["| " + " | ".join(row) + " |" for row in df.to_numpy()])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--labs", nargs="*", default=DEFAULT_LABS)
    parser.add_argument("--variant", default="protocol", choices=list(C.VARIANTS))
    args = parser.parse_args()

    labs = {}
    for run in args.labs:
        data = load(run, args.variant)
        if data is None:
            print(f"{run}: no spectra or embeddings for the {args.variant} variant, skipped.")
        else:
            labs[run] = data
    if len(labs) < 2:
        raise SystemExit("Need at least two labs.")

    rows = []
    for a, b in itertools.combinations(labs, 2):
        shared = sorted((set(labs[a]["keys"]) & set(labs[b]["keys"])) - {""})
        in_a = np.isin(labs[a]["keys"], shared)
        in_b = np.isin(labs[b]["keys"], shared)
        for name in labs[a]["reps"]:
            if name not in labs[b]["reps"]:
                continue
            x_a, x_b = labs[a]["reps"][name], labs[b]["reps"][name]
            acc, n = separability(x_a, x_b)
            row = {"lab A": a, "lab B": b, "representation": name,
                   "all spectra: balanced accuracy": round(acc, 3), "spectra per lab": n,
                   "shared molecules": len(shared)}
            if in_a.sum() >= MIN_SHARED_SPECTRA and in_b.sum() >= MIN_SHARED_SPECTRA:
                acc_shared, n_shared = separability(x_a[in_a], x_b[in_b])
                row.update({"shared molecules: balanced accuracy": round(acc_shared, 3),
                            "shared: spectra per lab": n_shared})
            rows.append(row)

    df = pd.DataFrame(rows)
    OUT_DIR.mkdir(exist_ok=True)
    df.to_parquet(OUT_DIR / f"exp_d_lab_shift_{args.variant}.parquet", index=False)
    text = "\n".join([
        "# Experiment D: how different are the labs?",
        "",
        f"Generated by `scripts/exp_d_lab_shift.py`, variant `{args.variant}`. Logistic regression, "
        "5-fold cross-validation, the same number of spectra from both labs (at most "
        f"{MAX_PER_LAB}). Balanced accuracy 0.5 = the two labs look the same, 1.0 = fully separated. "
        "*Shared molecules* repeats the test on library-annotated spectra of molecules measured in both labs "
        f"(only when each lab has at least {MIN_SHARED_SPECTRA} of them), so that chemistry is held fixed.",
        "",
        markdown(df),
        "",
        "Labs differ in chemistry and in measurement at the same time, so a high accuracy on all spectra "
        "alone does not show an instrument effect. Library annotations are putative.",
    ])
    (OUT_DIR / f"RESULTS_lab_shift_{args.variant}.md").write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
