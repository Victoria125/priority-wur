"""Can DreaMS be tested for genome-metabolome linking with public data?

NPLinker-style linking (the papers Joana sent) connects molecular families to
gene cluster families through their presence in many strains, and is judged
on known BGC-spectrum links. A fair test of DreaMS for this task needs a
dataset that has (1) many strains with genomes, (2) known BGC-MS2 links and
(3) spectra that DreaMS itself accepts.

For every actinobacterial PoDP dataset whose GNPS job is on this laptop
(scripts/download_data.py gnps), this script counts the spectra with peaks and
how many of them pass DreaMS's own format A check, and puts that next to the
number of genomes and known links from the PoDP inventory.
"""
import tempfile
from pathlib import Path

import pandas as pd

import common as C
from prepare_data import passes_dreams_check

OUT_DIR = C.EXPERIMENT_DIR / "linking_feasibility"
PODP = C.REPO_DIR / "data" / "derived" / "podp_projects.csv"
MIN_GENOMES = 10          # strain variation needed for correlation-based linking
MIN_LINKS = 3
MIN_SHARE_IN_DOMAIN = 0.5

# The known BGC-MS2 links of the one usable dataset (Crüsemann et al. 2017),
# written by hand from the known_link column of data/derived/podp_bgc_ms2_links.csv,
# and the pattern that finds each molecule among the GNPS library hits.
KNOWN_LINKS = {
    "MSV000078836": {
        "staurosporine (BGC0000827)": "stauro",
        "cyclomarin (BGC0000333)": "cyclomarin",
        "desferrioxamine (BGC0000940)": "desferrioxamine|deferoxamine",
        "lomaiviticin (BGC0000241)": "lomaiviticin",
        "retimycin (BGC0001228)": "retimycin",
        "rifamycin S and W (BGC0000137, two links)": "rifamycin",
        "rosamicin (BGC0001830)": "rosamicin",
        "arenimycin (BGC0000198)": "arenimycin",
    },
}


def known_link_coverage(massive, spectra, library):
    """For each known link, how many library-annotated spectra of the molecule
    exist and how many of them pass DreaMS's own check."""
    by_id = {s["scans"]: s for s in spectra}
    rows = []
    for link, pattern in KNOWN_LINKS.get(massive, {}).items():
        hits = library[library["compound_name"].astype(str).str.contains(pattern, case=False, regex=True)]
        found = [by_id[c] for c in hits["cluster_index"] if c in by_id]
        rows.append({
            "MassIVE": massive,
            "known link": link,
            "annotated spectra": len(found),
            "pass DreaMS's own check": sum(passes_dreams_check(s) for s in found),
            "precursor m/z": ", ".join(sorted({f"{s['precursor_mz']:.0f}" for s in found})),
        })
    return rows


def markdown(df):
    df = df.fillna("").astype(str)
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    return "\n".join(lines + ["| " + " | ".join(row) + " |" for row in df.to_numpy()])


def main():
    podp = pd.read_csv(PODP)
    rows, link_rows = [], []
    for archive in sorted(C.LOCAL_GNPS_DIR.glob("*/*/download_clustered_spectra.zip")):
        massive, task = archive.parts[-3], archive.parts[-2]
        if not C.is_gnps_archive(archive):
            print(f"{massive}/{task}: not a usable GNPS job, skipped.")
            continue
        with tempfile.TemporaryDirectory() as tmp:
            paths = C.extract_gnps_archive(archive, Path(tmp))
            params = C.read_gnps_params(paths.get("params"))
            spectra = [s for s in C.read_mgf(paths["spectra"]) if len(s["mz"]) > 0]
            library = C.read_library_hits(paths.get("library"))
        link_rows += known_link_coverage(massive, spectra, library)
        n_ok = sum(passes_dreams_check(s) for s in spectra)
        projects = podp[podp["metabolomics_id"] == massive]
        rows.append({
            "MassIVE": massive,
            "GNPS task": task[:8],
            "PI": "; ".join(projects["pi"].astype(str).unique())[:40],
            "genomes": int(projects["n_genomes"].max()) if len(projects) else 0,
            "known BGC-MS2 links": int(projects["n_bgc_ms2_links"].sum()) if len(projects) else 0,
            "fragment tolerance (Da)": params.get("tolerance.Ion_tolerance", ""),
            "spectra with peaks": len(spectra),
            "pass DreaMS's own check": n_ok,
            "share": f"{n_ok / max(len(spectra), 1):.0%}",
        })
        print(rows[-1])

    df = pd.DataFrame(rows)
    df["usable for a linking test"] = [
        "yes" if (r["genomes"] >= MIN_GENOMES and r["known BGC-MS2 links"] >= MIN_LINKS
                  and r["pass DreaMS's own check"] >= MIN_SHARE_IN_DOMAIN * r["spectra with peaks"]) else "no"
        for _, r in df.iterrows()
    ]
    OUT_DIR.mkdir(exist_ok=True)
    df.to_parquet(OUT_DIR / "linking_feasibility.parquet", index=False)
    text = "\n".join([
        "# Can DreaMS be tested for genome-metabolome linking with public data?",
        "",
        "Generated by `scripts/linking_feasibility.py` from the GNPS jobs of the actinobacterial PoDP "
        "datasets on this laptop and `data/derived/podp_projects.csv`. *Usable* means at least "
        f"{MIN_GENOMES} genomes (strain variation for correlation-based linking), at least {MIN_LINKS} "
        f"known BGC-MS2 links and at least {MIN_SHARE_IN_DOMAIN:.0%} of the spectra accepted by DreaMS's "
        "own format A check. These thresholds are our choice.",
        "",
        markdown(df.sort_values(["usable for a linking test", "known BGC-MS2 links"], ascending=False)),
        "",
        "## Known links of the usable dataset: can DreaMS see the molecules?",
        "",
        "Library-annotated spectra of each linked molecule, and how many pass DreaMS's own check. "
        "Format A accepts only charge +1 and precursor m/z up to 1000, so large or doubly charged "
        "molecules are out of the DreaMS domain.",
        "",
        markdown(pd.DataFrame(link_rows)) if link_rows else "No known links checked.",
    ])
    if link_rows:
        pd.DataFrame(link_rows).to_parquet(OUT_DIR / "known_link_coverage.parquet", index=False)
    (OUT_DIR / "RESULTS_linking_feasibility.md").write_text(text + "\n", encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
